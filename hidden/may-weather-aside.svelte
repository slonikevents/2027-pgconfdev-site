  <h2 id="may-weather" class="over">May in Montréal</h2>

  <p>
    Mid-May is mild but changeable: daytime highs around 18&nbsp;°C
    (65&nbsp;°F), dropping into the single digits after dark, with the odd rainy
    day. Pack layers, a light jacket for the evenings, and something for the
    rain.
  </p>
